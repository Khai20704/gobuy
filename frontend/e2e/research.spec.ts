test('missing search configuration explains setup instead of claiming no product exists', async ({ page }) => {
  await page.route('**/api/research/search', async route => {
    const response = await route.fetch(), result = await response.json()
    await route.fulfill({ response, json: { ...result, mode: 'real', status: 'SETUP_REQUIRED', recommendations: [], researchedCount: 0, eligibleCount: 0,
      summary: 'Live search is not connected yet. Na has not searched for this product, so this is not a no-match result.',
      nextStep: 'Connect an independent live search source in backend/.env, then restart the backend.', warnings: [], providers: [],
    } })
  })
  await page.goto('/na')
  await page.getByLabel('Your request to Na').fill('find me jordan 1 under 100 usd')
  await page.getByRole('button', { name: 'Send request', exact: true }).click()
  await expect(page.getByText('SEARCH NOT CONNECTED', { exact: true })).toBeVisible()
  await expect(page.getByText('Connect an independent live search source in backend/.env, then restart the backend.', { exact: true })).toBeVisible()
  await expect(page.locator('.research-card')).toHaveCount(0)
  await page.screenshot({ path: 'test-results/research-setup.png', fullPage: true })
})

