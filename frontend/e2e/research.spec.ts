test('total AI outage shows a safe Na message without raw provider details or fabricated products', async ({ page }) => {
  await page.route('**/api/research/search', route => route.fulfill({ status: 503, contentType: 'application/json',
    body: JSON.stringify({ error: { code: 'ALL_LLM_PROVIDERS_UNAVAILABLE', retryable: true,
      message: "Na's AI providers are temporarily unavailable. Please try again shortly." } }),
  }))
  await page.goto('/na')
  await page.getByLabel('Your request to Na').fill('Find Jordan 1 under 1 SOL')
  await page.getByRole('button', { name: 'Send request', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText("Na's AI providers are temporarily unavailable")
  await expect(page.getByRole('alert')).not.toContainText(/OpenAI|quota|stack/)
  await expect(page.locator('.research-card')).toHaveCount(0)
})
